"""Estimate secondary structure with SESCA from MRE spectra prepared by merge.py."""

from __future__ import annotations

import argparse
import os
import sys
import tempfile
from math import isfinite
from pathlib import Path
from zipfile import BadZipFile

from openpyxl import load_workbook
from openpyxl.styles import Font
from openpyxl.worksheet.worksheet import Worksheet

from merge import MRE_SHEET, PARAMETERS_SHEET, finite_number
from sesca_integration import (
    FIT_SHEET, RESULTS_SHEET, SescaOptions, fit_spectra, plot_sesca_results, write_results,
)


def read_mre(sheet: Worksheet) -> tuple[list[str], list[list[float | None]]]:
    """Read numeric MRE without applying concentration or unit conversion again."""
    headers = [cell.value for cell in sheet[1]]
    if headers[0] != "wavelength_nm":
        raise ValueError(f"{MRE_SHEET} must start with wavelength_nm. Check concentration_table.txt and rerun merge.py.")
    names = headers[1:]
    if not names:
        raise ValueError(f"No spectra in {MRE_SHEET}. Check concentration_table.txt and rerun merge.py.")
    if any(not isinstance(name, str) or not name.strip() for name in names):
        raise ValueError(f"Spectra in {MRE_SHEET} must have nonempty names.")
    if len(set(names)) != len(names):
        raise ValueError(f"Duplicate spectrum names in {MRE_SHEET}.")
    if sheet.max_row < 2:
        raise ValueError(f"No wavelength rows in {MRE_SHEET}.")
    rows = [
        [finite_number(row[0]), *[finite_number(cell, allow_blank=True) for cell in row[1:]]]
        for row in sheet.iter_rows(min_row=2)
    ]
    return names, rows


def deconvolve_spectra(
    folder: Path, *, sesca_options: SescaOptions | None = None, plot: bool = False,
) -> Path:
    """Fit existing MRE spectra, preserving their values and conversion metadata."""
    folder = Path(folder).resolve()
    workbook_file = folder.parent / f"{folder.name}-combined.xlsx"
    merge_command = f'python merge.py --folder "{folder}"'
    if not workbook_file.is_file():
        raise FileNotFoundError(
            f"Combined workbook not found: {workbook_file}\nRun merge.py first: {merge_command}"
        )

    workbook = load_workbook(workbook_file, data_only=False)
    temporary_path = None
    try:
        if MRE_SHEET not in workbook.sheetnames:
            raise ValueError(
                f"{workbook_file} has no {MRE_SHEET} sheet. Check the MRE settings in "
                f"concentration_table.txt. Run merge.py first: {merge_command}"
            )
        names, mre_rows = read_mre(workbook[MRE_SHEET])
        analysis = fit_spectra(names, mre_rows, sesca_options if sesca_options is not None else SescaOptions())

        for title in (RESULTS_SHEET, FIT_SHEET):
            if title in workbook.sheetnames:
                del workbook[title]
        write_results(workbook, analysis)

        if PARAMETERS_SHEET in workbook.sheetnames:
            parameters = workbook[PARAMETERS_SHEET]
            # Replace fitting metadata while retaining the original conversion parameters.
            for row in range(parameters.max_row, 1, -1):
                key = parameters.cell(row, 1).value
                if isinstance(key, str) and (key.startswith("sesca_") or key == "secondary_structure_analysis"):
                    parameters.delete_rows(row)
        else:
            parameters = workbook.create_sheet(PARAMETERS_SHEET)
            parameters.append(("parameter", "value"))
            parameters.column_dimensions["A"].width = 30
            parameters.column_dimensions["B"].width = 85
            for cell in parameters[1]:
                cell.font = Font(bold=True)
        for row in analysis.parameters:
            parameters.append(row)

        # Replace the source only after fitting and the entire write succeed.
        with tempfile.NamedTemporaryFile(
            prefix=f".{workbook_file.stem}-", suffix=".xlsx", dir=workbook_file.parent, delete=False,
        ) as temporary:
            temporary_path = Path(temporary.name)
        workbook.save(temporary_path)
        workbook.close()
        os.replace(temporary_path, workbook_file)
    finally:
        workbook.close()
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)
    if plot:
        plot_sesca_results(workbook_file)
    return workbook_file


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Estimate secondary structure with SESCA from the MRE sheet generated by merge.py."
    )
    parser.add_argument("--folder", type=Path, required=True, help="Data folder passed to merge.py.")
    parser.add_argument(
        "--plot", action="store_true",
        help="Display secondary-structure percentages from SESCA_results after saving.",
    )
    parser.add_argument(
        "--sesca-dir", type=Path,
        help="SESCA root containing scripts/ and libs/. Default: SESCA_HOME or .sesca/SESCA_v097.",
    )
    parser.add_argument(
        "--sesca-basis", default="DS-dT",
        help="Standalone SESCA basis name or path to a basis file (default: DS-dT).",
    )
    parser.add_argument("--sesca-min-nm", type=float, default=190.0, help="Fit range lower bound (default: 190 nm).")
    parser.add_argument("--sesca-max-nm", type=float, default=250.0, help="Fit range upper bound (default: 250 nm).")
    parser.add_argument("--sesca-repeats", type=int, default=10, help="Number of fit restarts (default: 10).")
    parser.add_argument("--sesca-seed", type=int, default=0, help="Random seed for repeatable fits (default: 0).")
    parser.add_argument(
        "--shared-scaling", nargs="?", type=float, const=True, default=False, metavar="FACTOR",
        help="Share one scaling factor: optimize it automatically without a value, "
             "or hold a positive FACTOR fixed for all fitted spectra.",
    )
    args = parser.parse_args()
    fixed_scaling = args.shared_scaling if not isinstance(args.shared_scaling, bool) else None
    if fixed_scaling is not None and (not isfinite(fixed_scaling) or fixed_scaling <= 0):
        parser.error("--shared-scaling FACTOR must be finite and greater than zero.")

    try:
        sesca_options = SescaOptions(
            directory=args.sesca_dir, basis=args.sesca_basis,
            min_nm=args.sesca_min_nm, max_nm=args.sesca_max_nm,
            repeats=args.sesca_repeats, seed=args.sesca_seed,
            shared_scaling=args.shared_scaling is not False, fixed_scaling=fixed_scaling,
        )
        output_file = deconvolve_spectra(args.folder, sesca_options=sesca_options, plot=args.plot)
    except (OSError, ValueError, RuntimeError, BadZipFile) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"Saved {RESULTS_SHEET} and {FIT_SHEET} in {output_file}.")
    print("Check status and note for any skipped spectra.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
