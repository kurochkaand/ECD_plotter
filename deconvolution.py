"""Convert corrected CD spectra to MRE and estimate secondary structure with SESCA."""

from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from math import isfinite
from numbers import Real
from pathlib import Path
from zipfile import BadZipFile

from openpyxl import load_workbook
from openpyxl.cell.cell import Cell
from openpyxl.styles import Font
from openpyxl.utils import get_column_letter
from openpyxl.utils.cell import coordinate_from_string, column_index_from_string
from openpyxl.worksheet.worksheet import Worksheet

from sesca_integration import (
    FIT_SHEET, RESULTS_SHEET, SescaOptions, fit_spectra, write_results,
)


SOURCE_SHEET = "CD_subtr"
MRE_SHEET = "MRE"
PARAMETERS_SHEET = "MRE_parameters"
MRE_UNITS = "deg cm^2 dmol^-1 (per residue)"
FORMULA_SOURCE = "https://pmc.ncbi.nlm.nih.gov/articles/PMC2728378/"
CELL_REFERENCE = r"\$?[A-Z]+\$?[1-9][0-9]*"
SUBTRACTION = re.compile(rf"=({CELL_REFERENCE})-({CELL_REFERENCE})")
NORMALIZED_SUBTRACTION = re.compile(
    rf"=\(({CELL_REFERENCE})-({CELL_REFERENCE})\)/"
    r"([0-9]+(?:\.[0-9]*)?(?:[eE][+-]?[0-9]+)?)"
)


def finite_number(cell: Cell, *, allow_blank: bool = False) -> float | None:
    """Reject spreadsheet errors, formulas, text, and nonfinite measurements."""
    value = cell.value
    if value is None and allow_blank:
        return None
    if isinstance(value, Real) and not isinstance(value, bool) and isfinite(value):
        return float(value)
    raise ValueError(
        f"{cell.parent.title}!{cell.coordinate}: expected a finite numeric value, "
        f"found {value!r}."
    )


def corrected_cd_value(cell: Cell, separator_column: int) -> float | None:
    """Evaluate only the subtraction formulas generated by merge.py, without Excel."""
    if cell.data_type != "f":
        return finite_number(cell, allow_blank=True)

    match = SUBTRACTION.fullmatch(cell.value)
    coefficient = 1.0
    if match is None:
        match = NORMALIZED_SUBTRACTION.fullmatch(cell.value)
        if match is not None:
            coefficient = float(match[3])
    if match is None or not isfinite(coefficient) or coefficient <= 0:
        raise ValueError(
            f"{cell.parent.title}!{cell.coordinate}: unsupported CD formula "
            f"{cell.value!r}. Rerun merge.py to regenerate the corrected spectra."
        )

    values = []
    for reference in match.group(1, 2):
        coordinate = reference.replace("$", "")
        column, row = coordinate_from_string(coordinate)
        # merge.py references measured inputs at the same wavelength only.
        if row != cell.row or not 2 <= column_index_from_string(column) < separator_column:
            raise ValueError(
                f"{cell.parent.title}!{cell.coordinate}: CD formula must reference "
                "input cells on the same wavelength row. Rerun merge.py."
            )
        values.append(finite_number(cell.parent[coordinate], allow_blank=True))
    if None in values:
        return None
    return (values[0] - values[1]) / coefficient


def read_corrected_cd(sheet: Worksheet) -> tuple[list[str], list[list[float | None]]]:
    """Read the corrected block after the zero separator, retaining excluded points."""
    headers = [cell.value for cell in sheet[1]]
    if headers[0] != "wavelength_nm" or headers.count("zero") != 1:
        raise ValueError(
            f"{SOURCE_SHEET} must start with wavelength_nm and contain one zero "
            "separator. Rerun merge.py first."
        )
    separator_column = headers.index("zero") + 1
    spectrum_names = headers[separator_column:]
    if not spectrum_names:
        raise ValueError(f"No corrected CD spectra after the zero separator in {SOURCE_SHEET}.")
    if any(not isinstance(name, str) or not name.strip() for name in spectrum_names):
        raise ValueError(f"Corrected spectra in {SOURCE_SHEET} must have nonempty names.")
    if len(set(spectrum_names)) != len(spectrum_names):
        raise ValueError(f"Duplicate corrected spectrum names in {SOURCE_SHEET}.")
    if sheet.max_row < 2:
        raise ValueError(f"No wavelength rows in {SOURCE_SHEET}.")

    rows = []
    for row_number in range(2, sheet.max_row + 1):
        wavelength = finite_number(sheet.cell(row_number, 1))
        values = [
            corrected_cd_value(sheet.cell(row_number, column), separator_column)
            for column in range(separator_column + 1, sheet.max_column + 1)
        ]
        rows.append([wavelength, *values])
    return spectrum_names, rows


def convert_to_mre(
    folder: Path, *, path_in_mm: float, num_of_aa: int, concentration_in_M: float,
    sesca_options: SescaOptions | None = None,
) -> Path:
    """Append numeric MRE spectra using the concentration targeted by merge.py."""
    for name, value in (("path_in_mm", path_in_mm), ("concentration_in_M", concentration_in_M)):
        if not isfinite(value) or value <= 0:
            raise ValueError(f"{name} must be finite and greater than zero.")
    if isinstance(num_of_aa, bool) or not isinstance(num_of_aa, int) or num_of_aa <= 0:
        raise ValueError("num_of_aa must be a positive integer.")
    denominator = path_in_mm * concentration_in_M * num_of_aa
    if not isfinite(denominator) or denominator <= 0:
        raise ValueError("The MRE conversion denominator must be finite and greater than zero.")

    folder = Path(folder).resolve()
    workbook_file = folder.parent / f"{folder.name}-combined.xlsx"
    if not workbook_file.is_file():
        raise FileNotFoundError(
            f"Combined workbook not found: {workbook_file}\n"
            f'Run merge.py first: python merge.py --folder "{folder}"'
        )

    workbook = load_workbook(workbook_file, data_only=False)
    temporary_path = None
    try:
        if SOURCE_SHEET not in workbook.sheetnames:
            raise ValueError(f"{workbook_file} has no {SOURCE_SHEET} sheet. Run merge.py first.")
        names, cd_rows = read_corrected_cd(workbook[SOURCE_SHEET])
        mre_rows = []
        for wavelength, *values in cd_rows:
            converted = [None if value is None else value / denominator for value in values]
            if any(value is not None and not isfinite(value) for value in converted):
                raise ValueError(f"Nonfinite MRE result at wavelength {wavelength:g} nm.")
            mre_rows.append([wavelength, *converted])

        analysis = fit_spectra(names, mre_rows, sesca_options) if sesca_options is not None else None

        # Reruns replace only these output sheets and retain all measured channels.
        for title in (MRE_SHEET, PARAMETERS_SHEET, RESULTS_SHEET, FIT_SHEET):
            if title in workbook.sheetnames:
                del workbook[title]
        output = workbook.create_sheet(MRE_SHEET)
        output.append(["wavelength_nm", *names])
        for row in mre_rows:
            output.append(row)
        output.freeze_panes = "B2"
        output.column_dimensions["A"].width = 18
        for column in range(2, output.max_column + 1):
            output.column_dimensions[get_column_letter(column)].width = 28
        for cell in output[1]:
            cell.font = Font(bold=True)
        for row in output.iter_rows(min_row=2, min_col=2):
            for cell in row:
                cell.number_format = "0.000000"

        parameters = workbook.create_sheet(PARAMETERS_SHEET)
        for row in (
            ("parameter", "value"),
            ("source_sheet", SOURCE_SHEET),
            ("source_block", "Corrected spectra after the zero separator"),
            ("path_in_mm", path_in_mm),
            ("num_of_aa", num_of_aa),
            ("concentration_in_mM", concentration_in_M * 1000.0),
            ("concentration_in_M", concentration_in_M),
            ("concentration_basis", "Peptide/protein molecules at the concentration targeted by merge.py"),
            ("MRE_units", MRE_UNITS),
            ("conversion", "CD_mdeg / (path_in_mm * concentration_in_M * num_of_aa)"),
            ("formula_source", FORMULA_SOURCE),
        ):
            parameters.append(row)
        if analysis is None:
            parameters.append(("secondary_structure_analysis", "Not run (MRE only)"))
        else:
            for row in analysis.parameters:
                parameters.append(row)
            write_results(workbook, analysis)
        parameters.column_dimensions["A"].width = 30
        parameters.column_dimensions["B"].width = 85
        for cell in parameters[1]:
            cell.font = Font(bold=True)

        # Save beside the source and replace it only after the entire write succeeds.
        with tempfile.NamedTemporaryFile(
            prefix=f".{workbook_file.stem}-", suffix=".xlsx", dir=workbook_file.parent, delete=False
        ) as temporary:
            temporary_path = Path(temporary.name)
        workbook.save(temporary_path)
        workbook.close()
        os.replace(temporary_path, workbook_file)
    finally:
        workbook.close()
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)
    return workbook_file


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Convert corrected CD to MRE and estimate secondary structure with SESCA."
    )
    parser.add_argument("--folder", type=Path, required=True, help="Data folder passed to merge.py.")
    parser.add_argument("--path-in-mm", type=float, required=True, help="Cell path length in millimeters.")
    parser.add_argument("--num-of-aa", type=int, required=True, help="Number of amino acid residues per molecule.")
    parser.add_argument(
        "--concentration-in-mM", type=float, required=True, dest="concentration_in_mM",
        help="Peptide/protein concentration in millimolar before dilution correction "
             "(the concentration targeted by merge.py's relative coefficients).",
    )
    parser.add_argument("--mre-only", action="store_true", help="Convert to MRE without running SESCA.")
    parser.add_argument(
        "--sesca-dir", type=Path,
        help="SESCA root containing scripts/ and libs/. Default: SESCA_HOME or .sesca/SESCA_v097.",
    )
    parser.add_argument(
        "--sesca-basis", default="DS-dT",
        help="Standalone SESCA basis name or path to a basis file (default: DS-dT).",
    )
    parser.add_argument("--sesca-min-nm", type=float, default=190.0, help="Fit range lower bound (default: 190 nm).")
    parser.add_argument("--sesca-max-nm", type=float, default=250.0, help="Fit range upper bound (default: 250 nm).")
    parser.add_argument("--sesca-repeats", type=int, default=10, help="Number of fit restarts (default: 10).")
    parser.add_argument("--sesca-seed", type=int, default=0, help="Random seed for repeatable fits (default: 0).")
    args = parser.parse_args()

    try:
        sesca_options = None if args.mre_only else SescaOptions(
            directory=args.sesca_dir, basis=args.sesca_basis,
            min_nm=args.sesca_min_nm, max_nm=args.sesca_max_nm,
            repeats=args.sesca_repeats, seed=args.sesca_seed,
        )
        output_file = convert_to_mre(
            args.folder, path_in_mm=args.path_in_mm, num_of_aa=args.num_of_aa,
            concentration_in_M=args.concentration_in_mM / 1000.0,
            sesca_options=sesca_options,
        )
    except (OSError, ValueError, RuntimeError, BadZipFile) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"Saved {MRE_SHEET} ({MRE_UNITS}) and {PARAMETERS_SHEET} in {output_file}")
    if sesca_options is not None:
        print(f"Saved {RESULTS_SHEET} and {FIT_SHEET}. Check status and note for any skipped spectra.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
