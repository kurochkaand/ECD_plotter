def finite_number(cell: Cell, *, allow_blank: bool = False) -> float | None:
    """Reject spreadsheet errors, formulas, text, and nonfinite measurements."""
    value = cell.value
    # pandas represents missing cells as empty strings until the workbook is saved.
    if allow_blank and value in (None, ""):
        return None
    if isinstance(value, Real) and not isinstance(value, bool) and isfinite(value):
        return float(value)
    raise ValueError(
        f"{cell.parent.title}!{cell.coordinate}: expected a finite numeric value, "
        f"found {value!r}."
    )


def corrected_cd_value(cell: Cell, separator_column: int) -> float | None:
    """Evaluate only the subtraction formulas generated by merge.py, without Excel."""
    if cell.data_type != "f":
        return finite_number(cell, allow_blank=True)

    match = SUBTRACTION.fullmatch(cell.value)
    concentration_in_mM = 1.0
    if match is None:
        match = NORMALIZED_SUBTRACTION.fullmatch(cell.value)
        if match is not None:
            concentration_in_mM = float(match[3])
    if match is None or not isfinite(concentration_in_mM) or concentration_in_mM <= 0:
        raise ValueError(
            f"{cell.parent.title}!{cell.coordinate}: unsupported CD formula "
            f"{cell.value!r}. Rerun merge.py to regenerate the corrected spectra."
        )

    values = []
    for reference in match.group(1, 2):
        coordinate = reference.replace("$", "")
        column, row = coordinate_from_string(coordinate)
        # merge.py references measured inputs at the same wavelength only.
        if row != cell.row or not 2 <= column_index_from_string(column) < separator_column:
            raise ValueError(
                f"{cell.parent.title}!{cell.coordinate}: CD formula must reference "
                "input cells on the same wavelength row. Rerun merge.py."
            )
        values.append(finite_number(cell.parent[coordinate], allow_blank=True))
    if None in values:
        return None
    return (values[0] - values[1]) / concentration_in_mM


def read_corrected_cd(sheet: Worksheet) -> tuple[list[str], list[list[float | None]]]:
    """Read the corrected block after the zero separator, retaining excluded points."""
    headers = [cell.value for cell in sheet[1]]
    if headers[0] != "wavelength_nm" or headers.count("zero") != 1:
        raise ValueError(
            f"{SOURCE_SHEET} must start with wavelength_nm and contain one zero "
            "separator. Rerun merge.py first."
        )
    separator_column = headers.index("zero") + 1
    spectrum_names = headers[separator_column:]
    if not spectrum_names:
        raise ValueError(f"No corrected CD spectra after the zero separator in {SOURCE_SHEET}.")
    if any(not isinstance(name, str) or not name.strip() for name in spectrum_names):
        raise ValueError(f"Corrected spectra in {SOURCE_SHEET} must have nonempty names.")
    if len(set(spectrum_names)) != len(spectrum_names):
        raise ValueError(f"Duplicate corrected spectrum names in {SOURCE_SHEET}.")
    if sheet.max_row < 2:
        raise ValueError(f"No wavelength rows in {SOURCE_SHEET}.")

    rows = []
    for row_number in range(2, sheet.max_row + 1):
        wavelength = finite_number(sheet.cell(row_number, 1))
        values = [
            corrected_cd_value(sheet.cell(row_number, column), separator_column)
            for column in range(separator_column + 1, sheet.max_column + 1)
        ]
        rows.append([wavelength, *values])
    return spectrum_names, rows


def mre_denominator(*, path_in_mm: float, num_of_aa: int, concentration_in_M: float) -> float:
    """Validate the absolute sample parameters before touching output files."""
    for name, value in (("path_in_mm", path_in_mm), ("concentration_in_M", concentration_in_M)):
        if not isfinite(value) or value <= 0:
            raise ValueError(f"{name} must be finite and greater than zero.")
    if isinstance(num_of_aa, bool) or not isinstance(num_of_aa, int) or num_of_aa <= 0:
        raise ValueError("num_of_aa must be a positive integer.")
    denominator = path_in_mm * concentration_in_M * num_of_aa
    if not isfinite(denominator) or denominator <= 0:
        raise ValueError("The MRE conversion denominator must be finite and greater than zero.")

    return denominator


def write_mre_spectra(
    workbook: Workbook, *, path_in_mm: float, num_of_aa: int, concentration_in_M: float,
    sample_concentrations: pd.Series | None = None,
) -> None:
    """Write numeric MRE and conversion metadata from the corrected CD block."""
    denominator = mre_denominator(
        path_in_mm=path_in_mm, num_of_aa=num_of_aa, concentration_in_M=concentration_in_M,
    )
    names, cd_rows = read_corrected_cd(workbook[SOURCE_SHEET])
    mre_rows = []
    for wavelength, *values in cd_rows:
        converted = [None if value is None else value / denominator for value in values]
        if any(value is not None and not isfinite(value) for value in converted):
            raise ValueError(f"Nonfinite MRE result at wavelength {wavelength:g} nm.")
        mre_rows.append([wavelength, *converted])

    output = workbook.create_sheet(MRE_SHEET)
    output.append(["wavelength_nm", *names])
    for row in mre_rows:
        output.append(row)
    output.freeze_panes = "B2"
    output.column_dimensions["A"].width = 18
    for column in range(2, output.max_column + 1):
        output.column_dimensions[get_column_letter(column)].width = 28
    for cell in output[1]:
        cell.font = Font(bold=True)
    for row in output.iter_rows(min_row=2, min_col=2):
        for cell in row:
            cell.number_format = "0.000000"

    parameters = workbook.create_sheet(PARAMETERS_SHEET)
    for row in (
        ("parameter", "value"),
        ("source_sheet", SOURCE_SHEET),
        ("source_block", "Corrected spectra after the zero separator"),
        ("pathlength_in_mm", path_in_mm),
        ("number_of_amino_acids", num_of_aa),
        ("concentration_basis", "Peptide/protein molecules in each measured sample"),
        ("MRE_units", MRE_UNITS),
        ("formula_source", FORMULA_SOURCE),
    ):
        parameters.append(row)
    if sample_concentrations is None:
        parameters.append(("concentration_in_mM", concentration_in_M * 1000.0))
        parameters.append(("concentration_in_M", concentration_in_M))
        parameters.append(("source_units", "mdeg"))
        parameters.append(("conversion", "CD_mdeg / (pathlength_in_mm * concentration_in_M * number_of_amino_acids)"))
    else:
        parameters.append(("source_units", "mdeg/mM (already concentration-normalized)"))
        parameters.append(("conversion", "CD_subtr * 1000 / (pathlength_in_mm * number_of_amino_acids)"))
        for name, concentration in sample_concentrations.items():
            parameters.append((f"concentration_in_mM[{name}]", float(concentration)))
            parameters.append((f"concentration_in_M[{name}]", float(concentration) / 1000.0))
    parameters.append(("secondary_structure_analysis", "Not run (MRE only)"))
    parameters.column_dimensions["A"].width = 30
    parameters.column_dimensions["B"].width = 85
    for cell in parameters[1]:
        cell.font = Font(bold=True)


def read_acquisition_datetime(file: Path) -> datetime:
    """Read YY/MM/DD and a 24-hour or AM/PM time from cells B5 and B6."""
    with file.open(encoding="latin-1", newline="") as stream:
        rows = list(islice(csv.reader(stream), 6))
    date_text = rows[4][1].strip() if len(rows) > 4 and len(rows[4]) > 1 else ""
    time_text = rows[5][1].strip() if len(rows) > 5 and len(rows[5]) > 1 else ""

    for date_format in ("%y/%m/%d", "%Y/%m/%d"):
        for time_format in ("%H:%M:%S", "%I:%M:%S %p"):
            try:
                return datetime.strptime(
                    f"{date_text} {time_text}", f"{date_format} {time_format}"
                )
            except ValueError:
                continue
    raise ValueError(
        f"Invalid acquisition date/time in {file}\n"
        f"  B5 (CSV line 5): {date_text!r}; expected YY/MM/DD or YYYY/MM/DD\n"
        f"  B6 (CSV line 6): {time_text!r}; expected HH:MM:SS or H:MM:SS AM/PM"
    )


def list_spectral_files(folder: Path) -> list[Path]:
    """Discover CSV files without reading spectra that may be excluded."""
    if not folder.is_dir():
        raise NotADirectoryError(f"Data folder not found: {folder}")

    files = [file for file in folder.glob("*.csv") if file.is_file()]
    if not files:
        raise FileNotFoundError(f"No CSV files found directly inside {folder}")
    return files


def find_spectral_files(
    folder: Path, *, included_names: set[str] | None = None,
) -> list[Path]:
    """Order included CSV files by acquisition date/time, earliest first."""
    files = list_spectral_files(folder)
    if included_names is not None:
        files = [file for file in files if file.stem in included_names]
    return sorted(
        files, key=lambda file: (read_acquisition_datetime(file), file.name.casefold()),
    )


def read_spectrum(file: Path) -> pd.DataFrame:
    """Read the block between XYDATA and Extended Information."""
    lines = file.read_text(encoding="latin-1").splitlines(keepends=True)
    data_start = None
    data_end = None
    for row_number, line in enumerate(lines):
        if line.strip() == "XYDATA":
            data_start = row_number + 1
        elif line.startswith("##### Extended Information"):
            data_end = row_number
            break

    if data_start is None:
        raise ValueError(f"XYDATA marker not found in {file}")
    if data_end is None:
        raise ValueError(f"Extended Information marker not found in {file}")

    data_block = "".join(lines[data_start:data_end])
    if not data_block.strip():
        raise ValueError(f"No spectral data found in {file}")

    frame = pd.read_csv(
        StringIO(data_block),
        header=None,
        index_col=False,
        skip_blank_lines=True,
    )
    if frame.shape[1] < 3:
        raise ValueError(
            f"Expected wavelength, CD, and HT columns with optional Abs in {file}; "
            f"found {frame.shape[1]} columns"
        )
    # Older three-column exports have no absorbance; keep their epsilon cells blank.
    frame = frame.reindex(columns=range(len(SPECTRAL_COLUMNS)))
    frame.columns = SPECTRAL_COLUMNS
    frame.attrs["csv_lines"] = [
        row_number + 1
        for row_number in range(data_start, data_end)
        if lines[row_number].strip()
    ]
    frame.attrs["data_end_line"] = data_end + 1
    return frame


def validate_wavelength_axis(
    reference: pd.DataFrame,
    actual: pd.DataFrame,
    reference_file: Path,
    actual_file: Path,
) -> None:
    """Report the first differing wavelength using physical CSV line numbers."""
    expected_axis = reference["wavelength_nm"].tolist()
    actual_axis = actual["wavelength_nm"].tolist()
    for row in range(max(len(expected_axis), len(actual_axis))):
        has_expected = row < len(expected_axis)
        has_actual = row < len(actual_axis)
        expected_value = expected_axis[row] if has_expected else None
        actual_value = actual_axis[row] if has_actual else None
        if has_expected and has_actual and expected_value == actual_value:
            continue

        expected_line = (
            reference.attrs["csv_lines"][row]
            if has_expected else reference.attrs["data_end_line"]
        )
        actual_line = (
            actual.attrs["csv_lines"][row]
            if has_actual else actual.attrs["data_end_line"]
        )
        expected_text = (
            f"{expected_value!r} nm" if has_expected else "<end of spectral data>"
        )
        actual_text = f"{actual_value!r} nm" if has_actual else "<end of spectral data>"
        raise ValueError(
            f"X axis mismatch in {actual_file}\n"
            f"  Reference file: {reference_file}\n"
            f"  Spectral data row: {row + 1}\n"
            f"  Expected: {expected_text} (CSV line {expected_line})\n"
            f"  Actual:   {actual_text} (CSV line {actual_line})\n"
            f"  Data rows: expected {len(expected_axis)}, actual {len(actual_axis)}"
        )


def extract_ph_from_name(spectrum_name: str) -> float | None:
    """Read a pH number from a filename stem, allowing a space after pH."""
    match = re.search(
        r"(?:^|[_\s-])ph\s*([+-]?(?:\d+(?:\.\d+)?|\.\d+))(?=$|[_\s-])",
        spectrum_name,
        flags=re.IGNORECASE,
    )
    return float(match.group(1)) if match else None


def determine_short_names(
    sample_names: list[str], subtraction_reference: str | None = None,
) -> dict[str, str]:
    """Remove shared filename affixes, keeping nonempty, unique spectrum labels."""
    full_names = dict(zip(sample_names, sample_names))
    samples = [name for name in sample_names if name != subtraction_reference]
    if len(samples) < 2:
        return full_names

    prefix = commonprefix(samples)
    remainders = [name[len(prefix):] for name in samples]
    suffix = commonprefix([name[::-1] for name in remainders])[::-1]
    shortened = {
        name: remainder[:len(remainder) - len(suffix)].strip(" _-\t")
        for name, remainder in zip(samples, remainders)
    }
    labels = full_names | shortened
    # Keep original stems if trimming removes a whole name or creates ambiguity.
    # The reference retains its full stem and never participates in affix detection.
    if (
        not all(labels.values())
        or len(set(labels.values())) != len(labels)
        or any(label in {"zero", "wavelength_nm"} for label in shortened.values())
        or subtraction_reference in shortened.values()
    ):
        return full_names
    return labels


def load_concentration_table(
    folder: Path, sample_names: list[str], *,
    subtraction_reference: str | None = None,
) -> pd.DataFrame:
    """Create defaults once; read existing sample selections without rewriting."""
    concentration_file = folder / "concentration_table.txt"
    created = not concentration_file.exists()
    settings = DEFAULT_MRE_SETTINGS.copy()
    if created:
        concentration_table = pd.DataFrame(
            {
                "spectrum": [name for name in sample_names if name != subtraction_reference],
                "concentration_in_mM": 1.0,
            }
        )
    else:
        with concentration_file.open(encoding="utf-8-sig", newline="") as stream:
            settings = {}
            header = []
            for line in stream:
                stripped = line.strip()
                if not stripped or stripped.startswith("#"):
                    continue
                key, separator, value = stripped.partition("=")
                if not separator:
                    header = next(csv.reader([line], delimiter="\t"))
                    break
                key = key.strip()
                if key not in DEFAULT_MRE_SETTINGS:
                    raise ValueError(f"Unknown MRE setting {key!r} in {concentration_file}.")
                if key in settings:
                    raise ValueError(f"Duplicate MRE setting {key!r} in {concentration_file}.")
                try:
                    settings[key] = int(value.strip()) if key == "number_of_amino_acids" else float(value.strip())
                except ValueError as exc:
                    raise ValueError(f"Invalid {key} in {concentration_file}: {value.strip()!r}.") from exc
            missing = [key for key in DEFAULT_MRE_SETTINGS if key not in settings]
            if missing:
                raise ValueError(
                    f"{concentration_file} is missing MRE settings: {', '.join(missing)}. "
                    "Add pathlength_in_mm = 1 and number_of_amino_acids = 1 above the table "
                    "and set them to your sample values. Rename concentration_coefficient to "
                    "concentration_in_mM and enter each sample's actual concentration in mM."
                )
            # Accept extra alignment tabs in a manually edited header.
            header = [column.strip() for column in header if column.strip()]
            column_count = len(header)
            if column_count not in (2, 3, 4):
                raise ValueError(
                    f"{concentration_file} must have two, three, or four tab-separated columns: "
                    "spectrum, concentration_in_mM, optional pH and short name"
                )
            if [name.casefold() for name in header] != [
                name.casefold() for name in CONCENTRATION_COLUMNS[:column_count]
            ]:
                raise ValueError(
                    f"{concentration_file} must use the columns "
                    + ", ".join(CONCENTRATION_COLUMNS[:column_count])
                    + ". Rename concentration_coefficient to concentration_in_mM and "
                    "enter each sample's actual concentration in mM."
                )
            rows = []
            for fields in csv.reader(stream, delimiter="\t"):
                if fields and fields[0].lstrip().startswith("#"):
                    continue
                fields = [field.strip() for field in fields]
                if not any(fields):
                    continue
                while fields and not fields[-1]:
                    fields.pop()
                # Legacy tables use repeated tabs for alignment. Four-column
                # rows also allow a blank pH cell before the short name.
                if column_count < 4 or len(fields) > column_count or (len(fields) > 1 and not fields[1]):
                    fields = [field for field in fields if field]
                if len(fields) > column_count:
                    raise ValueError(
                        f"{concentration_file} must have {column_count} tab-separated columns "
                        "per row; found extra values"
                    )
                rows.append([field or None for field in fields] + [None] * (column_count - len(fields)))
            concentration_table = pd.DataFrame(rows, columns=CONCENTRATION_COLUMNS[:column_count])
        concentration_table["spectrum"] = (
            concentration_table["spectrum"].astype(str).str.strip()
        )
        if concentration_table["spectrum"].duplicated().any():
            duplicates = concentration_table.loc[
                concentration_table["spectrum"].duplicated(), "spectrum"
            ].tolist()
            raise ValueError(
                f"Duplicate spectra in {concentration_file}: {', '.join(duplicates)}"
            )

    pathlength = settings["pathlength_in_mm"]
    residue_count = settings["number_of_amino_acids"]
    if not isfinite(pathlength) or pathlength <= 0:
        raise ValueError(f"pathlength_in_mm in {concentration_file} must be finite and greater than zero.")
    if residue_count <= 0:
        raise ValueError(f"number_of_amino_acids in {concentration_file} must be a positive integer.")

    # References from older tables are accepted but never treated as samples.
    concentration_table = concentration_table[
        concentration_table["spectrum"] != subtraction_reference
    ].copy()
    extra_spectra = [
        name for name in concentration_table["spectrum"] if name not in sample_names
    ]
    if extra_spectra:
        raise ValueError(
            f"{concentration_file} lists spectra not present in data folder: "
            + ", ".join(extra_spectra)
        )
    if concentration_table.empty:
        raise ValueError(f"No sample spectra listed in {concentration_file}.")

    inferred_ph = concentration_table["spectrum"].map(extract_ph_from_name).astype(float)
    if "pH" not in concentration_table:
        concentration_table["pH"] = inferred_ph.fillna(7.0)
    else:
        concentration_table["pH"] = concentration_table["pH"].fillna(
            inferred_ph
        ).fillna(7.0)

    concentration_table["concentration_in_mM"] = pd.to_numeric(
        concentration_table["concentration_in_mM"], errors="coerce"
    )
    concentrations = concentration_table.set_index("spectrum")[
        "concentration_in_mM"
    ]
    invalid = concentrations[
        ~concentrations.map(isfinite) | (concentrations <= 0)
    ].index.tolist()
    if invalid:
        raise ValueError(
            "Sample concentrations in mM must be finite and greater than zero for: "
            + ", ".join(invalid)
        )
    concentration_table = concentration_table.set_index("spectrum")
    included_names = [name for name in sample_names if name in concentration_table.index]
    concentration_table = concentration_table.loc[included_names]
    default_names = pd.Series(determine_short_names(included_names, subtraction_reference))
    if "short name" not in concentration_table:
        concentration_table["short name"] = default_names
    else:
        concentration_table["short name"] = concentration_table["short name"].fillna(default_names)
    labels = concentration_table["short name"]
    if labels.duplicated().any():
        duplicates = labels[labels.duplicated()].tolist()
        raise ValueError(f"Duplicate short names in {concentration_file}: {', '.join(duplicates)}")
    reserved = {"zero", "wavelength_nm", subtraction_reference}
    invalid_labels = labels[labels.isin(reserved)].tolist()
    if invalid_labels:
        raise ValueError(
            f"Short names in {concentration_file} conflict with workbook headers: "
            + ", ".join(invalid_labels)
        )
    if created:
        with concentration_file.open("x", encoding="utf-8", newline="") as stream:
            for key, value in settings.items():
                stream.write(f"{key} = {value:g}\n")
            stream.write("\n")
            concentration_table.to_csv(stream, sep="\t", index=True)
        print(f"Created {concentration_file}")
    concentration_table.attrs.update(settings)
    return concentration_table


def load_sample_concentrations(
    folder: Path, sample_names: list[str], *,
    subtraction_reference: str | None = None,
) -> pd.Series:
    """Return absolute concentrations in mM for the selected samples."""
    return load_concentration_table(
        folder, sample_names,
        subtraction_reference=subtraction_reference,
    )["concentration_in_mM"]


def select_subtraction_reference(sample_names: list[str], prefix: str | None) -> str | None:
    """Require one matching spectrum only when subtraction is requested."""
    if prefix is None:
        return None
    normalized_prefix = prefix.strip().casefold()
    if not normalized_prefix:
        raise ValueError("The --subtract filename prefix cannot be empty.")
    matches = [name for name in sample_names if name.casefold().startswith(normalized_prefix)]
    if len(matches) != 1:
        details = f": {', '.join(matches)}" if matches else ""
        raise ValueError(
            f"Expected exactly one spectrum starting with {prefix!r}; "
            f"found {len(matches)}{details}"
        )
    return matches[0]


def corrected_spectral_columns(
    spectral_data: dict[str, pd.Series],
    concentrations: pd.Series,
    subtraction_reference: str | None,
) -> list[pd.Series]:
    """Normalize a channel, using Excel formulas when subtracting a reference."""
    if subtraction_reference is None:
        return [
            (signal / concentrations[name]).rename(name)
            for name, signal in spectral_data.items()
        ]

    reference_column = get_column_letter(list(spectral_data).index(subtraction_reference) + 2)
    corrected_columns = []
    for column, (name, signal) in enumerate(spectral_data.items(), start=2):
        if name == subtraction_reference:
            continue
        source_column = get_column_letter(column)
        concentration_in_mM = float(concentrations[name])
        formulas = []
        for position, row in enumerate(range(2, len(signal) + 2)):
            if pd.isna(signal.iloc[position]) or pd.isna(spectral_data[subtraction_reference].iloc[position]):
                formulas.append(None)
                continue
            difference = f"{source_column}{row}-${reference_column}{row}"
            formulas.append(
                f"={difference}" if concentration_in_mM == 1.0
                else f"=({difference})/{concentration_in_mM!r}"
            )
        corrected_columns.append(pd.Series(formulas, index=signal.index, name=name))
    return corrected_columns


def smooth_cd_spectra(
    cd_data: dict[str, pd.Series], window_points: int, *, allow_gaps: bool = False
) -> dict[str, pd.Series]:
    """Apply quadratic Savitzky-Golay fits without padding or shifting samples."""
    if window_points < 3:
        raise ValueError("The --smooth window must contain at least 3 points for polynomial order 2.")
    for name, signal in cd_data.items():
        if window_points > len(signal):
            raise ValueError(
                f"The --smooth window of {window_points} points exceeds the "
                f"{len(signal)} data points in {name}.csv."
            )

    left = window_points // 2
    right = window_points - left - 1
    weights = savgol_coeffs(window_points, polyorder=2, pos=left, use="dot")
    window_positions = np.arange(window_points, dtype=float)
    smoothed_data = {}
    for name, signal in cd_data.items():
        try:
            values = signal.to_numpy(dtype=float)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"CD values in {name}.csv must be numeric for smoothing.") from exc
        if np.isinf(values).any() or (not allow_gaps and np.isnan(values).any()):
            raise ValueError(f"CD values in {name}.csv must be finite for smoothing.")

        smoothed = values.copy()
        # Never bridge excluded points. Keep short valid runs unsmoothed.
        boundaries = np.flatnonzero(np.diff(np.r_[False, ~np.isnan(values), False]))
        for start, stop in zip(boundaries[::2], boundaries[1::2]):
            if stop - start < window_points:
                continue
            segment = values[start:stop]
            smoothed[start + left:stop - right] = np.convolve(segment, weights[::-1], mode="valid")
            # Fit only measured points at each valid segment's edges.
            first_fit = np.polynomial.Polynomial.fit(window_positions, segment[:window_points], 2)
            last_fit = np.polynomial.Polynomial.fit(window_positions, segment[-window_points:], 2)
            smoothed[start:start + left] = first_fit(window_positions[:left])
            smoothed[stop - right:stop] = last_fit(window_positions[-right:])
        smoothed_data[name] = pd.Series(smoothed, index=signal.index, name=signal.name)
    return smoothed_data


def epsilon_spectra(
    absorbance_data: dict[str, pd.Series], concentrations: pd.Series,
    subtraction_reference: str | None, *, path_in_mm: float, num_of_aa: int,
) -> dict[str, pd.Series]:
    """Convert HT-filtered absorbance to numeric, per-residue epsilon spectra."""
    numeric_data = {}
    for name, signal in absorbance_data.items():
        try:
            numeric_data[name] = pd.to_numeric(signal, errors="raise")
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Absorbance values in {name}.csv must be numeric.") from exc
        if np.isinf(numeric_data[name]).any():
            raise ValueError(f"Absorbance values in {name}.csv must be finite or blank.")

    converted = {}
    # c_M = c_mM / 1000; l_cm = l_mm / 10; epsilon_res = A / (c_M * l_cm * N).
    factor = 10.0 / mre_denominator(
        path_in_mm=path_in_mm, num_of_aa=num_of_aa, concentration_in_M=0.001,
    )
    if not isfinite(factor):
        raise ValueError("The epsilon conversion factor must be finite.")
    for name, signal in numeric_data.items():
        if name == subtraction_reference:
            continue
        if subtraction_reference is not None:
            signal = signal - numeric_data[subtraction_reference]
        epsilon = signal / concentrations[name] * factor
        if np.isinf(epsilon).any():
            raise ValueError(f"Nonfinite epsilon result for {name}.")
        converted[name] = epsilon.rename(name)
    return converted


def plot_corrected_spectra(
    wavelengths: pd.Series,
    spectral_channels: dict[str, dict[str, pd.Series]],
    concentrations: pd.Series,
    subtraction_reference: str | None,
    *, smooth_window: int | None = None, ht_threshold: float | None = None,
    short_names: dict[str, str] | None = None,
    mre_divisor: float | None = None,
) -> None:
    """Display corrected CD in MRE alongside already-converted epsilon spectra."""
    import matplotlib.pyplot as plt

    sample_names = [name for name in spectral_channels["CD"] if name != subtraction_reference]
    if not sample_names:
        raise ValueError("No sample spectra remain to plot after reference subtraction.")

    corrected_channels = {}
    for channel_name, spectral_data in spectral_channels.items():
        corrected = {}
        for name in sample_names:
            signal = spectral_data[name]
            if channel_name == "CD":
                if subtraction_reference is not None:
                    signal = signal - spectral_data[subtraction_reference]
                signal = signal / concentrations[name]
                if mre_divisor is not None:
                    signal = signal / mre_divisor
            corrected[name] = signal
        # Missing or fully excluded absorbance produces no epsilon curve.
        if channel_name == EPSILON_SHEET:
            corrected = {name: signal for name, signal in corrected.items() if signal.notna().any()}
            if not corrected:
                continue
        corrected_channels[channel_name] = corrected

    figure, axes = plt.subplots(
        len(corrected_channels), 1, figsize=(14, 6 * len(corrected_channels)),
        sharex=True, squeeze=False,
    )
    try:
        colors = plt.get_cmap("turbo")
        for axis, (channel_name, corrected) in zip(axes[:, 0], corrected_channels.items()):
            for index, name in enumerate(sample_names):
                if name not in corrected:
                    continue
                axis.plot(
                    wavelengths,
                    corrected[name],
                    label=short_names[name] if short_names is not None else name,
                    linewidth=1.3,
                    color=colors(index / max(len(sample_names) - 1, 1)),
                )

            label = "CD" if channel_name == "CD" else "absorbance"
            title = f"Concentration-normalized {label} spectra"
            if channel_name == "CD" and mre_divisor is not None:
                title = "CD spectra (MRE)"
            elif channel_name == EPSILON_SHEET:
                title = "Absorbance spectra (epsilon per residue)"
            if subtraction_reference is not None:
                title += f"\nReference subtracted: {subtraction_reference}"
            if channel_name == "CD" and smooth_window is not None:
                title += f"\nSavitzky-Golay: {smooth_window} points, polynomial order 2"
            if ht_threshold is not None:
                title += f"\nHT cutoff: {ht_threshold:g} V"
            axis.set_title(title)
            axis.set_xlabel("Wavelength (nm)")
            if channel_name == "CD" and mre_divisor is not None:
                axis.set_ylabel(r"MRE (deg cm$^2$ dmol$^{-1}$ per residue)")
            elif channel_name == EPSILON_SHEET:
                axis.set_ylabel(r"$\varepsilon$ (M$^{-1}$ cm$^{-1}$ per residue)")
            else:
                axis.set_ylabel("Normalized CD (mdeg/mM)")
            axis.grid(alpha=0.25)
            axis.legend(loc="upper left", bbox_to_anchor=(1.02, 1), fontsize=7)
        figure.tight_layout()
        plt.show(block=True)
    finally:
        plt.close(figure)


def merge_spectra(
    folder: Path, *, subtract: str | None = None,
    plot: bool = False, smooth: int | None = None, ht_threshold: float | None = None,
) -> Path:
    """Write corrected CD, MRE, and epsilon using the concentration table."""
    if ht_threshold is not None and (not isfinite(ht_threshold) or ht_threshold < 0):
        raise ValueError("The --ht-threshold value must be finite and greater than or equal to zero.")
    available_names = [file.stem for file in list_spectral_files(folder)]
    subtraction_reference = select_subtraction_reference(available_names, subtract)
    concentration_table = None
    included_names = None
    if (folder / "concentration_table.txt").exists():
        concentration_table = load_concentration_table(
            folder, available_names, subtraction_reference=subtraction_reference,
        )
        included_names = set(concentration_table.index)
        if subtraction_reference is not None:
            included_names.add(subtraction_reference)
    files = find_spectral_files(folder, included_names=included_names)
    reference_frame: pd.DataFrame | None = None
    channel_columns: dict[str, list[pd.Series]] = {
        sheet_name: [] for sheet_name in CHANNEL_SHEETS
    }
    cd_data: dict[str, pd.Series] = {}
    abs_data: dict[str, pd.Series] = {}

    for file in files:
        frame = read_spectrum(file)
        if reference_frame is None:
            reference_frame = frame
            for columns in channel_columns.values():
                columns.append(frame["wavelength_nm"])
        else:
            validate_wavelength_axis(reference_frame, frame, files[0], file)

        if ht_threshold is not None:
            try:
                ht_values = pd.to_numeric(frame["ht_v"], errors="raise")
            except (TypeError, ValueError) as exc:
                raise ValueError(f"HT values in {file} must be numeric for --ht-threshold.") from exc
            if not np.isfinite(ht_values).all():
                raise ValueError(f"HT values in {file} must be finite for --ht-threshold.")
            excluded = ht_values > ht_threshold
            frame["cd_mdeg"] = frame["cd_mdeg"].mask(excluded)
            frame["absorbance"] = frame["absorbance"].mask(excluded)

        for sheet_name, column_name in CHANNEL_SHEETS.items():
            channel_columns[sheet_name].append(frame[column_name].rename(file.stem))
        cd_data[file.stem] = frame["cd_mdeg"]
        abs_data[file.stem] = frame["absorbance"]

    sample_names = list(cd_data)
    if smooth is not None:
        cd_data = smooth_cd_spectra(cd_data, smooth, allow_gaps=ht_threshold is not None)
    if concentration_table is None:
        concentration_table = load_concentration_table(
            folder, sample_names, subtraction_reference=subtraction_reference,
        )
    concentrations = concentration_table["concentration_in_mM"]
    path_in_mm = concentration_table.attrs["pathlength_in_mm"]
    num_of_aa = concentration_table.attrs["number_of_amino_acids"]
    # CD_subtr is already divided by each sample's concentration in mM.
    # Convert that 1 mM-normalized signal to MRE without dividing by concentration again.
    mre_divisor = mre_denominator(
        path_in_mm=path_in_mm, num_of_aa=num_of_aa, concentration_in_M=0.001,
    )
    short_names = concentration_table["short name"].to_dict()

    epsilon_data = epsilon_spectra(
        abs_data, concentrations, subtraction_reference,
        path_in_mm=path_in_mm, num_of_aa=num_of_aa,
    )
    wavelengths = channel_columns["CD"][0]
    cd_summary = pd.concat(
        [
            wavelengths,
            *(cd_data[name].rename(name) for name in sample_names),
            pd.Series(0, index=wavelengths.index, name="zero"),
            *corrected_spectral_columns(cd_data, concentrations, subtraction_reference),
        ],
        axis=1,
    )

    output_file = folder.parent / f"{folder.name}-combined.xlsx"
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            prefix=f".{output_file.stem}-", suffix=".xlsx", dir=output_file.parent, delete=False,
        ) as temporary:
            temporary_path = Path(temporary.name)
        with pd.ExcelWriter(temporary_path, engine="openpyxl") as writer:
            for sheet_name, columns in channel_columns.items():
                pd.concat(columns, axis=1).rename(columns=short_names).to_excel(
                    writer, sheet_name=sheet_name, index=False
                )
            cd_summary.rename(columns=short_names).to_excel(
                writer, sheet_name=SOURCE_SHEET, index=False,
            )
            write_mre_spectra(
                writer.book, path_in_mm=path_in_mm, num_of_aa=num_of_aa,
                concentration_in_M=0.001,
                sample_concentrations=concentrations.rename(index=short_names),
            )
            pd.concat([wavelengths, *epsilon_data.values()], axis=1).rename(
                columns=short_names,
            ).to_excel(writer, sheet_name=EPSILON_SHEET, index=False)
            writer.book[EPSILON_SHEET].freeze_panes = "B2"
            for row in (
                ("epsilon_sheet", EPSILON_SHEET),
                ("epsilon_units", EPSILON_UNITS),
                ("epsilon_conversion", "(sample_abs - reference_abs) * 10000 / "
                 "(concentration_in_mM * pathlength_in_mm * number_of_amino_acids)"),
                ("epsilon_formula_source", EPSILON_FORMULA_SOURCE),
                ("absorbance_reference", subtraction_reference or "None (reference_abs = 0)"),
                ("ht_threshold_V", ht_threshold if ht_threshold is not None else "Disabled"),
            ):
                writer.book[PARAMETERS_SHEET].append(row)
            if subtraction_reference is not None:
                writer.book.calculation = CalcProperties(
                    calcMode="auto", fullCalcOnLoad=True, forceFullCalc=True
                )
        os.replace(temporary_path, output_file)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)
    if plot:
        plot_corrected_spectra(
            wavelengths, {"CD": cd_data, EPSILON_SHEET: epsilon_data},
            concentrations, subtraction_reference,
            smooth_window=smooth, ht_threshold=ht_threshold, short_names=short_names,
            mre_divisor=mre_divisor,
        )
    return output_file


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Merge instrument CSV files into MRE and per-residue epsilon using concentration_table.txt."
    )
    parser.add_argument(
        "--folder",
        type=Path,
        default=DEFAULT_FOLDER,
        help="Data-folder override for DEFAULT_FOLDER configured in the script.",
    )
    parser.add_argument(
        "--subtract",
        metavar="PREFIX",
        help="Subtract the CD and absorbance reference matching this filename prefix before conversion.",
    )
    parser.add_argument(
        "--plot",
        action="store_true",
        help="Display CD in MRE and absorbance in epsilon per residue after saving.",
    )
    parser.add_argument(
        "--smooth",
        type=int,
        nargs="?",
        const=50,
        default=None,
        metavar="POINTS",
        help="Smooth CD before subtraction using Savitzky-Golay (order 2, no padding). "
             "Defaults to 50 points when supplied without a value.",
    )
    parser.add_argument(
        "--ht-threshold",
        type=float,
        nargs="?",
        const=500.0,
        default=None,
        metavar="VALUE",
        help="Remove CD and epsilon points where that spectrum's HT exceeds VALUE (V), before smoothing and conversion. "
             "Defaults to 500 when supplied without a value.",
    )
    args = parser.parse_args()

    try:
        output_file = merge_spectra(
            args.folder.resolve(), subtract=args.subtract,
            plot=args.plot, smooth=args.smooth, ht_threshold=args.ht_threshold,
        )
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"Saved {output_file}")
    print(f"Saved {MRE_SHEET} ({MRE_UNITS}) and {PARAMETERS_SHEET}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
